// Generates src/gpu/gen/com-tables.ts: IIDs and flattened vtable method orders for the COM interfaces we implement,
// extracted from the mingw-w64 headers (both widl-style C vtbl structs and DECLARE_INTERFACE_ blocks).
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const inc = "/usr/x86_64-w64-mingw32/include";
const headers = ["d3d9.h", "d3dcommon.h", "dxgi.h", "dxgi1_2.h", "dxgi1_3.h", "dxgi1_4.h", "dxgi1_5.h", "dxgi1_6.h", "d3d11.h", "d3d11_1.h", "d3d11_2.h", "d3d11_3.h", "d3d11_4.h",
  "mmdeviceapi.h", "audioclient.h", "xaudio2.h", "dsound.h", "dinput.h", "d3d10.h", "d3d11sdklayers.h", "dxgidebug.h", "unknwn.h", "objidl.h", "endpointvolume.h"];
const iids = new Map(); // name -> "xxxxxxxx-..."
const ifaces = new Map(); // name -> {parent, methods}

const hex = (s, n) => s.replace(/^0x/i, "").padStart(n, "0").toLowerCase();
for (const h of headers) {
  const p = join(inc, h);
  if (!existsSync(p)) continue;
  const src = readFileSync(p, "latin1");
  for (const m of src.matchAll(/DEFINE_GUID\(\s*IID_(\w+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,((?:\s*0x[0-9a-fA-F]+\s*,?){8})\s*\)/g)) {
    const d = m[5].split(",").map((x) => x.trim()).filter(Boolean).map((x) => hex(x, 2));
    iids.set(m[1], `${hex(m[2], 8)}-${hex(m[3], 4)}-${hex(m[4], 4)}-${d[0]}${d[1]}-${d.slice(2).join("")}`);
  }
  // widl style: typedef struct IFooVtbl { ... } IFooVtbl;
  for (const m of src.matchAll(/typedef struct (\w+)Vtbl\s*\{([\s\S]*?)\}\s*\1Vtbl;/g)) {
    const methods = [...m[2].matchAll(/\(\s*(?:STDMETHODCALLTYPE|WINAPI|__stdcall)\s*\*\s*(\w+)\s*\)\s*\(/g)].map((x) => x[1]);
    if (methods.length) ifaces.set(m[1], { methods });
  }
  // DECLARE_INTERFACE_(IFoo, IParent) { STDMETHOD...(Name)... }
  for (const m of src.matchAll(/DECLARE_INTERFACE_\(\s*(\w+)\s*,\s*(\w+)\s*\)\s*\{([\s\S]*?)\n\};/g)) {
    const methods = [...m[3].matchAll(/STDMETHOD(?:_\([^)]*?\))?\s*\(\s*(?:[\w\s]*,)?\s*(\w+)\s*\)|STDMETHOD_\(\s*[^,()]+(?:\([^)]*\))?\s*,\s*(\w+)\s*\)/g)].map((x) => x[1] ?? x[2]).filter(Boolean);
    // simpler robust extraction
    const names = [];
    for (const mm of m[3].matchAll(/STDMETHOD(_)?\s*\(([^)]*)\)/g)) {
      const inner = mm[2];
      names.push(mm[1] ? inner.split(",").pop().trim() : inner.trim());
    }
    void methods;
    if (names.length) ifaces.set(m[1], { parent: m[2], methods: names });
  }
}
// resolve inheritance for DECLARE_INTERFACE blocks that did not repeat the parent's methods
function full(name, seen = new Set()) {
  const it = ifaces.get(name);
  if (!it) return null;
  if (!it.parent || seen.has(name)) return it.methods;
  const parent = it.parent === "IUnknown" ? ["QueryInterface", "AddRef", "Release"] : full(it.parent, new Set([...seen, name]));
  if (!parent) return it.methods;
  const prefix = it.methods.slice(0, parent.length);
  if (prefix.every((x, i) => x === parent[i])) return it.methods;
  return [...parent, ...it.methods];
}
const out = {};
for (const [name] of ifaces) {
  const methods = full(name);
  const iid = iids.get(name);
  if (!methods) continue;
  out[name] = { iid: iid ?? null, methods };
}
const keys = Object.keys(out).sort();
const body = keys.map((k) => `  ${JSON.stringify(k)}: { iid: ${JSON.stringify(out[k].iid)}, methods: ${JSON.stringify(out[k].methods)} },`).join("\n");
writeFileSync(join(root, "src/gpu/gen/com-tables.ts"), `// Generated by scripts/gen-com.mjs from the mingw-w64 headers. Do not edit.\nexport const COM: Record<string, { iid: string | null; methods: string[] }> = {\n${body}\n};\n`);
console.log(`${keys.length} interfaces, ${[...iids].length} iids`);
for (const k of ["IDirect3DDevice9", "ID3D11Device", "ID3D11DeviceContext", "IDXGISwapChain", "IDirect3DSurface9", "IXAudio2", "IDirectSound8"]) console.log(k, out[k]?.methods.length, out[k]?.iid);
