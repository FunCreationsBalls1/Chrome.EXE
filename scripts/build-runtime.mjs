// Builds the C runtime helpers to WebAssembly and embeds them as src/gen/runtime-wasm.ts
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as L from "../src/jit/layout.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
mkdirSync(join(root, "build"), { recursive: true });
mkdirSync(join(root, "src/gen"), { recursive: true });

// layout.h
let h = "// GENERATED from src/jit/layout.ts by scripts/build-runtime.mjs. Do not edit.\n#pragma once\n";
for (const [k, v] of Object.entries(L)) {
  if (typeof v !== "number") continue;
  const name = k === "STATE" ? "STATE_BASE" : k === "LOOKUP" ? "LOOKUP_BASE" : k;
  if (!/^[A-Z_0-9]+$/.test(name)) continue;
  h += `#define ${name} ${v >>> 0}u\n`;
}
writeFileSync(join(root, "runtime/layout.h"), h);

const out = join(root, "build/runtime.wasm");
const args = [
  "--target=wasm32", "-O2", "-nostdlib", "-ffreestanding", "-fno-builtin-memcpy", "-fno-builtin-memset",
  "-msimd128", "-mbulk-memory", "-mnontrapping-fptoint", "-mtail-call", "-msign-ext", "-mmutable-globals",
  "-Wall", "-Wno-unused-function",
  "-Wl,--no-entry", "-Wl,--export-dynamic", "-Wl,--import-memory", "-Wl,--stack-first",
  "-Wl,-z,stack-size=3072", "-Wl,--global-base=65536", "-Wl,--initial-memory=1048576",
  "-Wl,--allow-undefined", "-Wl,--strip-all",
  "-o", out, join(root, "runtime/runtime.c"),
];
execFileSync("clang", args, { stdio: "inherit" });
const wasm = readFileSync(out);
const b64 = wasm.toString("base64");
writeFileSync(
  join(root, "src/gen/runtime-wasm.ts"),
  `// GENERATED by scripts/build-runtime.mjs from runtime/runtime.c. Do not edit.\nexport const RUNTIME_WASM_B64 = "${b64}";\n`,
);
console.log(`runtime.wasm: ${wasm.length} bytes`);
